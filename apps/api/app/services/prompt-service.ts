export class PromptService {
  /**
   * 视频文案润色/仿写的系统提示词。
   *
   * TODO: 占位提示词，后续补充具体的润色与仿写指令。
   */
  polishArticleSystemPrompt(transcript: string) {
    return ['你是一名专业的视频文案润色与仿写助手。', '', '请基于以下视频文案，结合用户的要求进行润色或仿写。', '', '视频文案如下：', '"""', transcript, '"""'].join('\n');
  }

  /**
   * 视频拆解任务的系统提示词。
   *
   * 要求模型将视频拆解为连续的时间片段，并以 JSON 数组形式返回
   */
  videoBreakdownSystemPrompt() {
    return [
      '你是一位专业的视频内容拆解分析师。你的任务是基于视频的视觉内容（镜头、场景、动作）将视频拆解为独立的分镜片段。',
      '一个“分镜”定义为：从一次镜头切换（剪辑点）开始，到下一次镜头切换结束的连续画面序列。',
      '分镜边界必须严格对齐到镜头切换点，而不应在同一镜头中间截断。',
      '如果视频中有明显的场景变化（如地点、时间跳跃）、主要角色进出画面、或动作段落起止，也应作为分镜划分依据。',
      '',
      '输出要求：',
      '- 只返回一个合法的 JSON 数组，数组元素为分镜对象，按 start 时间升序排列。',
      '- 每个分镜对象必须包含以下字段：',
      '  - "start": 分镜开始时间，格式 "HH:MM:SS.sss"（精确到毫秒，三位小数）',
      '  - "end": 分镜结束时间，格式 "HH:MM:SS.sss"（精确到毫秒，三位小数），且 end > start',
      '  - "summary": 用一句中文概述该分镜的核心视觉内容和动作（不超过30字）',
      '- 分镜之间不得重叠，且必须连续覆盖整个视频时间轴（第一个分镜 start 应为 00:00:00.000，最后一个分镜 end 应为视频总时长）。',
      '- 所有时间值必须与提供的抽帧时间戳精确匹配，尽量使边界落在抽帧点上。',
      '',
      '输出格式约束：',
      '- 严禁输出任何解释、注释、Markdown 标记（如 ```json）或其他文本，仅输出 JSON 数组本身。',
      '- 确保 JSON 格式有效，字段名用双引号，字符串用双引号，数值时间用字符串。',
      '',
      '示例（仅演示格式，勿照抄内容）：',
      '[{"start":"00:00:00.000","end":"00:00:05.200","summary":"全景展示城市天际线，镜头缓慢右移"},{"start":"00:00:05.200","end":"00:00:12.000","summary":"中景，主角从画面左侧走入，停下眺望"}]',
    ].join('\n');
  }
}
